def _apply_fictional_scenarios() -> None:
    """Point the mock providers at fixed scenarios for the fictional vendors."""
    from zentra.scanners.cve.provider import MockCveProvider
    from zentra.scanners.dns_sec.provider import MockDnsProvider
    from zentra.scanners.hibp.provider import MockBreachProvider
    from zentra.scanners.shodan.provider import MockExposureProvider
    from zentra.scanners.ssl_labs.provider import MockTlsProvider
    from zentra.scanners.technology.provider import MockTechnologyProvider

    mapping: dict[str, Any] = {
        "tls": MockTlsProvider,
        "dns": MockDnsProvider,
        "hibp": MockBreachProvider,
        "shodan": MockExposureProvider,
        "tech": MockTechnologyProvider,
        "cve": MockCveProvider,
    }
    for domain, scenarios in FICTIONAL_SCENARIOS.items():
        for key, scenario in scenarios.items():
            mapping[key].SCRIPTED[domain] = scenario


def _require_mock_providers() -> None:
    settings = get_settings()
    if not settings.use_mock_scanners:
        raise SystemExit(
            "Refusing to seed with USE_MOCK_SCANNERS=false.\n"
            "The demo dataset must never contain real scan results attributed to real "
            "companies. Set USE_MOCK_SCANNERS=true, or seed a different environment."
        )
    if settings.is_production:
        raise SystemExit("Refusing to seed a production environment.")


def seed(*, reset: bool = False) -> dict[str, str]:
    _require_mock_providers()
    _apply_fictional_scenarios()

    with session_scope() as session:
        existing = session.execute(
            select(Organization).where(Organization.name == DEMO_ORG)
        ).scalar_one_or_none()
        if existing is not None:
            if not reset:
                log.info("seed_already_present", organization_id=str(existing.id))
                return {
                    "organization_id": str(existing.id),
                    "email": DEMO_EMAIL,
                    "status": "already_seeded",
                }
            session.delete(existing)
            session.flush()

        user = session.execute(select(User).where(User.email == DEMO_EMAIL)).scalar_one_or_none()
        if user is None:
            from zentra.core.security import hash_password

            user = User(
                email=DEMO_EMAIL,
                full_name="Demo Operator",
                password_hash=hash_password(DEMO_PASSWORD),
                email_verified_at=datetime.now(UTC),
            )
            session.add(user)
            session.flush()

        organization = create_organization(
            session,
            name=DEMO_ORG,
            owner=user,
            industry="Fintech",
            company_size="10-50",
            country="GB",
            website_domain="northwind-payments.example.com",
        )
        organization.is_demo = True
        organization.plan = Plan.GROWTH.value
        organization.vendor_limit = PLANS[Plan.GROWTH].vendor_limit

        subscription = session.execute(
            select(Subscription).where(Subscription.organization_id == organization.id)
        ).scalar_one()
        subscription.plan = Plan.GROWTH.value
        subscription.status = "active"
        subscription.current_period_end = datetime.now(UTC) + timedelta(days=30)
        session.flush()

        created = 0
        for spec in DEMO_VENDORS:
            vendor = create_vendor(
                session,
                organization=organization,
                name=spec["name"],
                domain=spec["domain"],
                actor=user,
                description=spec["description"],
                category=spec["category"],
                criticality=spec["criticality"],
                owner_label=spec["owner_label"],
                is_demo=True,
            )
            # Run two scans so the demo has a visible score history.
            for index in range(2):
                scan = scans_service.queue_scan(
                    session, vendor=vendor, trigger="initial" if index == 0 else "scheduled"
                )
                scans_service.execute_scan(session, scan.id)
                if index == 0:
                    # Backdate the first scan so the trend chart has two points.
                    stored = session.get(Scan, scan.id)
                    if stored is not None:
                        stored.completed_at = datetime.now(UTC) - timedelta(days=7)
            created += 1

        session.flush()
        log.info(
            "seed_complete",
            organization_id=str(organization.id),
            vendors=created,
        )
        return {
            "organization_id": str(organization.id),
            "email": DEMO_EMAIL,
            "vendors": str(created),
            "status": "seeded",
        }


def main() -> int:
    parser = argparse.ArgumentParser(description="Seed Zentra demo data.")
    parser.add_argument(
        "--reset", action="store_true", help="Delete and recreate the demo organization."
    )
    args = parser.parse_args()

    settings = get_settings()
    configure_logging(settings.log_level, settings.log_format, service="zentra-seed")

    result = seed(reset=args.reset)
    print("\nDemo data ready.")
    print(f"  Organization : {DEMO_ORG}")
    print(f"  Sign in with : {DEMO_EMAIL}")
    print(f"  Password     : {DEMO_PASSWORD}")
    print(f"  Vendors      : {result.get('vendors', 'existing')}")
    print(
        "\nAll scan results in this dataset are synthetic fixtures produced by Zentra's mock\n"
        "providers. They are illustrative only and say nothing about the real security\n"
        "posture of any named company.\n"
    )
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
