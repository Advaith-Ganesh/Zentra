"""Demo data seeder.

Creates a fully populated demo organization so a new developer (or a sales
demo) has something realistic to look at immediately.

Everything created here is marked ``is_demo = True``, and every scanner result
comes from Zentra's deterministic **mock** providers. The vendor names below are
real, well-known SaaS companies used as realistic examples of a vendor stack —
the security findings attached to them are synthetic fixtures generated by the
mock providers and describe nothing about those companies' actual security
posture. The seeder refuses to run against real providers for exactly that
reason.
"""

